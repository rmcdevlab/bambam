import "server-only";
import { readdir, readFile } from "node:fs/promises";
import { resolve } from "node:path";
import type { Pool } from "pg";
export function migrationUp(source: string): string {
  if (/^--\s*\+goose\s+(NO TRANSACTION|ENVSUB)/m.test(source)) throw new Error("Unsupported Goose migration directive");
  const parts = source.split(/^--\s*\+goose\s+Up\s*$/m);
  if (parts.length !== 2) throw new Error("Migration must contain exactly one Goose Up marker");
  const up = parts[1].split(/^--\s*\+goose\s+Down\s*$/m)[0];
  // Send the full script in one query: preserve dollar-quoted PL/pgSQL and StatementBegin blocks.
  return up;
}
export async function migrate(database: Pool, directory = resolve(process.cwd(), "db/migrations")) {
  const client = await database.connect();
  try {
    await client.query("SELECT pg_advisory_lock(56002)");
    await client.query(`CREATE TABLE IF NOT EXISTS public.goose_db_version(
      id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      version_id bigint NOT NULL,is_applied boolean NOT NULL,tstamp timestamp DEFAULT now())`);
    const { rows: history } = await client.query<{ version_id: string; is_applied: boolean }>(
      "SELECT DISTINCT ON(version_id) version_id,is_applied FROM public.goose_db_version ORDER BY version_id,id DESC");
    const applied = new Set(history.filter(r => r.is_applied).map(r => String(r.version_id)));
    const files = (await readdir(directory)).filter(f => /^\d+_.+\.sql$/.test(f)).sort();
    const known = new Set(files.map(f => BigInt(f.split("_")[0]).toString()));
    if (known.size !== files.length) throw new Error("Duplicate migration version");
    for (const version of applied) if (version !== "0" && !known.has(version)) throw new Error("Applied migration missing from source directory");
    const completed: string[] = [];
    for (const file of files) {
      const version = BigInt(file.split("_")[0]).toString();
      if (applied.has(version)) continue;
      const sql = migrationUp(await readFile(resolve(directory, file), "utf8"));
      await client.query("BEGIN");
      try {
        await client.query(sql);
        await client.query("INSERT INTO public.goose_db_version(version_id,is_applied) VALUES($1,true)", [version]);
        await client.query("COMMIT"); completed.push(file);
      } catch (error) { await client.query("ROLLBACK"); throw error; }
    }
    return completed;
  } finally {
    try { await client.query("SELECT pg_advisory_unlock(56002)"); } finally { client.release(); }
  }
}
